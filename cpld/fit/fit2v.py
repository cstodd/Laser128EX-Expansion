#!/usr/bin/env python3
"""Turn the 'programmed logic' equations in an Atmel fitter report (.fit) back into Verilog,
so the RTL testbench can be run against exactly what the fitter put in the .jed.
Usage: fit2v.py out/laser128_ramcard.fit > out/fitted.v"""
import re, sys

src = open(sys.argv[1]).read()
blk = src.split('programmed logic:')[1].split('Pin/Node Placement')[0].split('\n', 2)[2]  # skip the ---- rule
eqs = [' '.join(e.split()) for e in blk.split(';') if '=' in e]

IN = 'rasb_n ecas1_n ecas2_n ecas3_n ecas4_n e1moe_n rwr_n era8 memrd pwr_rst_n'.split()
OUT = 'rowclk col_le ma8 ma17 ma18 ram_ce_n oe0_n oe1_n we0_n we1_n buf_oe_n dbg0'.split()
BIDI = ['xd_%d' % i for i in range(8)] + ['sda', 'scl']

def expr(e):
    e = e.replace('#', '|').replace('!', '~')
    e = re.sub(r'(\w+)\.Q\b', r'\1_q', e)
    e = re.sub(r'(\w+)\.PIN\b', r'\1', e)          # pin feedback = the pad value
    return e

comb, regs, oe = {}, {}, {}
for e in eqs:
    lhs, rhs = [s.strip() for s in e.split('=', 1)]
    neg = lhs.startswith('!'); lhs = lhs.lstrip('!')
    r = expr(rhs)
    if neg: r = '~(%s)' % r
    m = re.match(r'(\w+)\.(D|C|AR|AP|OE|CE)$', lhs)
    if m:
        n, k = m.groups()
        if k == 'OE': oe[n] = r
        else: regs.setdefault(n, {})[k] = r
    else:
        comb[lhs] = r

out = ['// generated by fit2v.py from %s: do not edit' % sys.argv[1], '`timescale 1ns/1ps',
       'module laser128_ramcard(input wire %s,' % ', '.join(IN),
       '  output wire %s,' % ', '.join(OUT),
       '  inout wire [7:0] xd, inout wire sda, inout wire scl);']
for i in range(8): out.append('  wire xd_%d; assign xd[%d] = xd_%d_oe ? xd_%d_v : 1\'bz; assign xd_%d = xd[%d];' % (i, i, i, i, i, i))
names = set(comb) | set(regs) | set(oe)
for n in sorted(names):
    if n in regs: out.append('  reg %s_q;' % n)
    if n in comb and n not in IN + OUT + BIDI: out.append('  wire %s;' % n)
for n, d in sorted(regs.items()):
    clk, ar = d['C'], d.get('AR', "1'b0")
    out.append('  wire %s_clk = %s, %s_ar = %s;' % (n, clk, n, ar))
    out.append('  always @(posedge %s_clk or posedge %s_ar) if (%s_ar) %s_q <= 0; else %s_q <= %s;'
               % (n, n, n, n, n, d['D']))
    if n in OUT: out.append('  assign %s = %s_q;' % (n, n))
for n, r in sorted(comb.items()):
    if n.startswith('xd_'): out.append("  wire %s_v = %s;" % (n, r))
    elif n in ('sda', 'scl'): out.append("  assign %s = %s ? (%s) : 1'bz;" % (n, oe[n], r))
    else: out.append('  assign %s = %s;' % (n, r))
for n, r in sorted(oe.items()):
    if n.startswith('xd_'): out.append('  wire %s_oe = %s;' % (n, r))
out.append('endmodule')
print('\n'.join(out))
